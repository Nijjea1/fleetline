"""E2/E3 report: tables (RESULTS.md) and chart (e2.png) from bench/e2/runs/*/summary.json.

    uv run --project ml python bench/e2/report.py
"""

import json
import re
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt

HERE = Path(__file__).parent
DAYS = {"09-16": "Sep 16 (calibration day)", "09-23": "Sep 23 (held out)"}
POLICIES = ("greedy", "batched")
COLORS = {"greedy": "#8b95a5", "batched": "#2f6fdb"}


def load():
    runs = {}
    for f in sorted(HERE.glob("runs/*/summary.json")):
        m = re.fullmatch(r"(\d\d-\d\d)_(\w+)_w(\d+)_s(\d+)", f.parent.name)
        if m:
            day, pol, w, seed = m.groups()
            runs[(day, pol, int(w), int(seed))] = json.loads(f.read_text())["summary"]
    return runs


def stats(s):
    return {
        "mean": s["sim_wait"]["mean_s"],
        "p50": s["sim_wait"]["p50_s"],
        "p90": s["sim_wait"]["p90_s"],
        "unserved": 100 * s["unserved_rate"],
        "pickup": s["pickup_eta"]["mean_s"],
        "requests": s["requests"],
    }


def pct(new, old):
    return f"{100 * (new - old) / old:+.1f}%"


def spread(vals, fmt="{:.0f}"):
    mid = sorted(vals)[len(vals) // 2]
    return fmt.format(mid) if len(vals) == 1 else f"{fmt.format(mid)} ({fmt.format(min(vals))}–{fmt.format(max(vals))})"


def main():
    runs = load()
    out = ["# E2 / E3 results", "", "Generated by `bench/e2/report.py` from `runs/*/summary.json`. Full simulated days "
           "(01:00–23:59), calibrated supply, 10-min pickup cap. Only the policy / window change between runs.", ""]

    # E2: 1 s window, seeds 7-9: median (min-max) across seeds.
    out += ["## E2: greedy vs batched (1 s dispatch window, 3 seeds)", "",
            "| Day | Policy | Mean wait (s) | p50 (s) | p90 (s) | Unserved (%) | Mean empty drive to pickup (s) |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    head = {}
    for day, label in DAYS.items():
        for pol in POLICIES:
            ss = [stats(runs[k]) for k in sorted(runs) if k[0] == day and k[1] == pol and k[2] == 1]
            if not ss:
                continue
            col = {m: [s[m] for s in ss] for m in ss[0]}
            head[(day, pol)] = {m: sorted(v)[len(v) // 2] for m, v in col.items()}
            out.append(f"| {label} | {pol} | {spread(col['mean'])} | {spread(col['p50'])} | {spread(col['p90'])} | "
                       f"{spread(col['unserved'], '{:.2f}')} | {spread(col['pickup'])} |")
    out.append("")
    for day, label in DAYS.items():
        g, b = head.get((day, "greedy")), head.get((day, "batched"))
        if g and b:
            out.append(f"- **{label}**: batched vs greedy (median of seeds): mean wait {pct(b['mean'], g['mean'])}, "
                       f"p50 {pct(b['p50'], g['p50'])}, p90 {pct(b['p90'], g['p90'])}, empty drive "
                       f"{pct(b['pickup'], g['pickup'])}, unserved {g['unserved']:.2f}% → {b['unserved']:.2f}% "
                       f"({g['requests']:,} requests)")
    out.append("")

    # E3: window sweep, seed 7.
    out += ["## E3: dispatch window (seed 7)", "",
            "| Day | Window (s) | Greedy mean / p90 (s) | Batched mean / p90 (s) | Batched vs greedy, mean |",
            "| --- | --- | --- | --- | --- |"]
    sweep = defaultdict(dict)
    for (day, pol, w, seed), s in runs.items():
        if seed == 7:
            sweep[(day, pol)][w] = stats(s)
    for day, label in DAYS.items():
        for w in sorted(sweep[(day, "greedy")]):
            g, b = sweep[(day, "greedy")].get(w), sweep[(day, "batched")].get(w)
            if g and b:
                out.append(f"| {label} | {w} | {g['mean']:.0f} / {g['p90']:.0f} | {b['mean']:.0f} / {b['p90']:.0f} | "
                           f"{pct(b['mean'], g['mean'])} |")
    (HERE / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))

    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8), sharey=True)
    for ax, (day, label) in zip(axes, DAYS.items()):
        for pol in POLICIES:
            pts = sorted(sweep[(day, pol)].items())
            if not pts:
                continue
            ws = [w for w, _ in pts]
            ax.plot(ws, [s["mean"] for _, s in pts], "o-", color=COLORS[pol], label=f"{pol}: mean")
            ax.plot(ws, [s["p90"] for _, s in pts], "s--", color=COLORS[pol], alpha=0.7, label=f"{pol}: p90")
        ax.set(title=label, xlabel="dispatch window (s)", xticks=[1, 2, 5, 10])
        ax.grid(alpha=0.3)
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].set_ylabel("rider wait (s)")
    axes[0].legend(frameon=False, fontsize=8)
    fig.suptitle("E2/E3 · greedy vs batched matching, full simulated day of real NYC requests")
    fig.tight_layout()
    fig.savefig(HERE / "e2.png", dpi=150)
    print(f"\n-> {HERE / 'e2.png'}")


if __name__ == "__main__":
    main()
